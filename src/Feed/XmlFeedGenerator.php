<?php
/**
 * Meta Catalog Compliant XML Feed Generator.
 *
 * @package WPCalibrate\CatalogSyncMeta
 */

namespace WPCalibrate\CatalogSyncMeta\Feed;

use WC_Product;
use WC_Product_Variation;
use XMLWriter;
use WPCalibrate\CatalogSyncMeta\Catalog\EligibilityEngine;
use WPCalibrate\CatalogSyncMeta\Catalog\ProductIdentifier;
use WPCalibrate\CatalogSyncMeta\Logging\Logger;
use WPCalibrate\CatalogSyncMeta\Mapping\FieldMapper;
use WPCalibrate\CatalogSyncMeta\Settings\SettingsRegistry;

defined( 'ABSPATH' ) || exit;

/**
 * Class XmlFeedGenerator
 */
class XmlFeedGenerator {

	/**
	 * Feed XML namespace for Google Shopping / Meta attributes.
	 */
	public const NS_GOOGLE = 'http://base.google.com/ns/1.0';

	/**
	 * Get the public URL for the XML feed.
	 *
	 * @return string
	 */
	public static function get_feed_url(): string {
		$token = (string) SettingsRegistry::get( 'feed_token', '' );
		return add_query_arg(
			array(
				'wpcalibrate_csm_feed' => '1',
				'token'                => $token,
			),
			home_url( '/' )
		);
	}

	/**
	 * Regenerate the secure feed access token.
	 *
	 * @return string New token.
	 */
	public static function regenerate_token(): string {
		$new_token = wp_generate_password( 32, false );
		SettingsRegistry::set( 'feed_token', $new_token );
		Logger::info( 'Feed token was regenerated by administrator.' );
		return $new_token;
	}

	/**
	 * Render or stream the XML feed directly to HTTP response.
	 *
	 * @param bool $stream Whether to send headers and stream out.
	 * @return string|void String XML if not streaming.
	 */
	public static function render_feed( bool $stream = true ) {
		$enabled = SettingsRegistry::get( 'enable_feed', true );
		if ( ! $enabled ) {
			if ( $stream ) {
				status_header( 403 );
				echo esc_html__( 'Product feed is disabled.', 'wpcalibrate-catalog-sync-meta' );
				exit;
			}
			return '';
		}

		if ( $stream ) {
			// Disable output buffering and configure streaming headers.
			if ( ob_get_level() ) {
				ob_end_clean();
			}

			header( 'Content-Type: application/xml; charset=utf-8' );
			header( 'X-Robots-Tag: noindex, follow', true );
			header( 'Cache-Control: public, max-age=3600' );
		}

		$writer = new XMLWriter();
		if ( $stream ) {
			$writer->openURI( 'php://output' );
		} else {
			$writer->openMemory();
		}

		$writer->startDocument( '1.0', 'UTF-8' );
		$writer->setIndent( true );
		$writer->setIndentString( '  ' );

		// <rss xmlns:g="http://base.google.com/ns/1.0" version="2.0">
		$writer->startElement( 'rss' );
		$writer->writeAttribute( 'xmlns:g', self::NS_GOOGLE );
		$writer->writeAttribute( 'version', '2.0' );

		// <channel>
		$writer->startElement( 'channel' );
		$writer->writeElement( 'title', get_bloginfo( 'name' ) . ' - Meta Product Catalog' );
		$writer->writeElement( 'link', home_url( '/' ) );
		$writer->writeElement( 'description', 'Product catalog feed for Meta/Facebook synchronized by WPCalibrate' );

		$item_count = 0;
		$page       = 1;
		$batch_size = 50;

		// Stream products in paginated batches to keep memory bounded.
		while ( true ) {
			$product_ids = wc_get_products(
				array(
					'limit'   => $batch_size,
					'page'    => $page,
					'status'  => 'publish',
					'type'    => array( 'simple', 'variable' ),
					'return'  => 'ids',
					'orderby' => 'ID',
					'order'   => 'ASC',
				)
			);

			if ( empty( $product_ids ) ) {
				break;
			}

			foreach ( $product_ids as $pid ) {
				$product = wc_get_product( $pid );
				if ( ! $product instanceof WC_Product ) {
					continue;
				}

				if ( ! EligibilityEngine::is_eligible( $product ) ) {
					continue;
				}

				if ( $product->is_type( 'variable' ) ) {
					$children = $product->get_children();
					foreach ( $children as $cid ) {
						$var = wc_get_product( $cid );
						if ( $var instanceof WC_Product_Variation && EligibilityEngine::is_eligible( $var ) ) {
							self::write_product_item( $writer, $var );
							$item_count++;
						}
					}
				} else {
					self::write_product_item( $writer, $product );
					$item_count++;
				}
			}

			$page++;
		}

		$writer->endElement(); // </channel>
		$writer->endElement(); // </rss>
		$writer->endDocument();

		SettingsRegistry::set( 'feed_last_generated', time() );
		SettingsRegistry::set( 'feed_item_count', $item_count );

		if ( $stream ) {
			$writer->flush();
			exit;
		}

		return $writer->outputMemory();
	}

	/**
	 * Write a single product or variation to XMLWriter.
	 *
	 * @param XMLWriter  $writer  Writer instance.
	 * @param WC_Product $product Product instance.
	 * @return void
	 */
	private static function write_product_item( XMLWriter $writer, WC_Product $product ): void {
		$mapped = FieldMapper::map_product( $product );

		$writer->startElement( 'item' );

		// Standard Meta/Google Shopping tags.
		$writer->writeElement( 'g:id', (string) $mapped['id'] );
		$writer->writeElement( 'g:title', (string) $mapped['title'] );
		$writer->writeElement( 'g:description', (string) $mapped['description'] );
		$writer->writeElement( 'g:link', (string) $mapped['link'] );
		$writer->writeElement( 'g:image_link', (string) $mapped['image_link'] );
		$writer->writeElement( 'g:availability', (string) $mapped['availability'] );
		$writer->writeElement( 'g:condition', (string) $mapped['condition'] );
		$writer->writeElement( 'g:price', (string) $mapped['price'] );

		if ( ! empty( $mapped['sale_price'] ) ) {
			$writer->writeElement( 'g:sale_price', (string) $mapped['sale_price'] );
		}

		if ( ! empty( $mapped['brand'] ) ) {
			$writer->writeElement( 'g:brand', (string) $mapped['brand'] );
		}

		if ( ! empty( $mapped['item_group_id'] ) ) {
			$writer->writeElement( 'g:item_group_id', (string) $mapped['item_group_id'] );
		}

		if ( ! empty( $mapped['google_product_category'] ) ) {
			$writer->writeElement( 'g:google_product_category', (string) $mapped['google_product_category'] );
		}

		if ( ! empty( $mapped['gtin'] ) ) {
			$writer->writeElement( 'g:gtin', (string) $mapped['gtin'] );
		}

		if ( ! empty( $mapped['mpn'] ) ) {
			$writer->writeElement( 'g:mpn', (string) $mapped['mpn'] );
		}

		if ( ! empty( $mapped['inventory'] ) ) {
			$writer->writeElement( 'g:inventory', (string) $mapped['inventory'] );
		}

		if ( ! empty( $mapped['additional_image_link'] ) && is_array( $mapped['additional_image_link'] ) ) {
			foreach ( $mapped['additional_image_link'] as $extra_img ) {
				$writer->writeElement( 'g:additional_image_link', (string) $extra_img );
			}
		}

		// Variation attributes (e.g., color, size).
		if ( ! empty( $mapped['color'] ) ) {
			$writer->writeElement( 'g:color', (string) $mapped['color'] );
		}
		if ( ! empty( $mapped['size'] ) ) {
			$writer->writeElement( 'g:size', (string) $mapped['size'] );
		}
		if ( ! empty( $mapped['material'] ) ) {
			$writer->writeElement( 'g:material', (string) $mapped['material'] );
		}
		if ( ! empty( $mapped['pattern'] ) ) {
			$writer->writeElement( 'g:pattern', (string) $mapped['pattern'] );
		}
		if ( ! empty( $mapped['gender'] ) ) {
			$writer->writeElement( 'g:gender', (string) $mapped['gender'] );
		}

		$writer->endElement(); // </item>
	}

	/**
	 * Intercept HTTP query for feed delivery.
	 *
	 * @return void
	 */
	public static function maybe_serve_feed(): void {
		// phpcs:ignore WordPress.Security.NonceVerification.Recommended
		if ( ! isset( $_GET['wpcalibrate_csm_feed'] ) ) {
			return;
		}

		$expected_token = (string) SettingsRegistry::get( 'feed_token', '' );
		// phpcs:ignore WordPress.Security.NonceVerification.Recommended
		$provided_token = isset( $_GET['token'] ) ? sanitize_text_field( wp_unslash( $_GET['token'] ) ) : '';

		if ( empty( $expected_token ) || empty( $provided_token ) || ! hash_equals( $expected_token, $provided_token ) ) {
			status_header( 401 );
			header( 'Content-Type: text/plain; charset=utf-8' );
			echo esc_html__( 'Unauthorized feed access token.', 'wpcalibrate-catalog-sync-meta' );
			exit;
		}

		self::render_feed( true );
	}
}
